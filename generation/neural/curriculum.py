def stage(key: str) -> CurriculumStage:
    """Return one stage by key."""
    for candidate in CURRICULUM:
        if candidate.key == key:
            return candidate
    raise ContractError(
        f"Unknown curriculum stage {key!r}. Declared: {', '.join(s.key for s in CURRICULUM)}."
    )


def validate_curriculum(stages: Sequence[CurriculumStage] | None = None) -> None:
    """Check the curriculum is consistent and acyclic.

    Three checks, each guarding a mistake that is cheap to make and expensive to
    discover during training: an objective that does not exist, a stage that
    depends on a later stage, and an objective used in a stage its own
    declaration does not list.
    """
    active = tuple(stages or CURRICULUM)
    keys = [s.key for s in active]
    if len(set(keys)) != len(keys):
        raise ContractError("Curriculum stage keys must be unique.")
    known_losses = {spec.name: spec for spec in LOSSES}
    position = {key: index for index, key in enumerate(keys)}
    for current in active:
        for objective in current.objectives:
            if objective not in known_losses:
                raise ContractError(
                    f"Stage {current.key} uses undeclared objective {objective!r}."
                )
            if current.key not in known_losses[objective].stages:
                raise ContractError(
                    f"Objective {objective!r} is used by stage {current.key} but does not list "
                    "it among its stages. One of the two declarations is wrong."
                )
        for dependency in current.blocked_by:
            if dependency not in position:
                raise ContractError(
                    f"Stage {current.key} depends on unknown stage {dependency!r}."
                )
            if position[dependency] >= position[current.key]:
                raise ContractError(
                    f"Stage {current.key} depends on {dependency!r}, which does not come before it."
                )


validate_curriculum()


def stages_without_external_data() -> tuple[str, ...]:
    """Stages that can start today, with no dataset and no licensing exposure."""
    return tuple(s.key for s in CURRICULUM if not s.external_data_required)
