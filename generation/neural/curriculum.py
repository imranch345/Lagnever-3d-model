"""Proposed training curriculum.

STATUS: PROPOSED. Declared as data so that the ordering can be argued with, and so
that a stage cannot quietly start before its inputs exist.

Revision of the sequence in the Step 5 brief
--------------------------------------------

The brief proposed nine stages. Six are proposed instead, and three changes are
deliberate:

1. **Text-to-anatomy is merged with text-anatomy alignment.** They share data,
   they share a model, and splitting them creates a checkpoint nobody uses.
2. **Anatomy-to-geometry correspondence is merged into geometry autoencoding.**
   The part-label head is trained with reconstruction; separating them invites a
   representation that reconstructs well and labels badly, which is the exact
   failure the project is trying to avoid.
3. **Images move to the end and become optional.** They are the hardest modality
   to licence and the only one that is not required for text-only inference. The
   first two stages need no external data at all, which means work can begin
   before any dataset decision is settled. That de-risks the schedule more than
   any modelling choice in this document.

Animation stays last, because it needs temporal data that does not exist yet, and
because a wrong cardiac cycle on a wrong heart teaches nothing.
"""

from __future__ import annotations

from collections.abc import Sequence
from dataclasses import dataclass

from awr.errors import ContractError
from generation.neural.losses import LOSSES, LossSpec, loss

__all__ = ["CurriculumStage", "CURRICULUM", "stage", "validate_curriculum"]


@dataclass(frozen=True, slots=True)
class CurriculumStage:
    """One stage of the proposed curriculum."""

    key: str
    title: str
    goal: str
    inputs: tuple[str, ...]
    objectives: tuple[str, ...]
    trains: tuple[str, ...]
    frozen: tuple[str, ...]
    exit_criteria: tuple[str, ...]
    external_data_required: bool
    blocked_by: tuple[str, ...] = ()
    status: str = "PROPOSED"

    def objective_specs(self) -> tuple[LossSpec, ...]:
        """Loss specifications for this stage."""
        return tuple(loss(name) for name in self.objectives)


