@dataclass(frozen=True, slots=True)
class PipelineStage:
    """One stage of the proposed pipeline."""

    name: str
    role: str
    interface: str
    consumes: tuple[str, ...]
    produces: tuple[str, ...]
    contract: str
    implemented: bool = False
    trainable: bool = True
    notes: str | None = None

    def describe(self) -> str:
        """One-line human-readable description."""
        mark = "implemented" if self.implemented else "declared"
        return f"{self.name} [{mark}]: {self.role}"


