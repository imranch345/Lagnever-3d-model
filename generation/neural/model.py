@dataclass(slots=True)
class LagnavArchitecture:
    """A composed, checkable description of the proposed model."""

    stages: tuple[PipelineStage, ...] = field(default_factory=lambda: LAGNAV_PIPELINE)
    scale_spec: ScaleSpec = field(default_factory=lambda: scale("prototype"))
    graph: GraphEncoderSpec = field(default_factory=GraphEncoderSpec)
    language: LanguageEncoderSpec = field(default_factory=LanguageEncoderSpec)
    geometry: GeometryTokenSpec = field(default_factory=GeometryTokenSpec)
    encoder: AnatomicalEncoderSpec = field(default_factory=AnatomicalEncoderSpec)
    status: str = "PROPOSED"

    def stage(self, name: str) -> PipelineStage:
        """Return one stage by name."""
        for candidate in self.stages:
            if candidate.name == name:
                return candidate
        raise ContractError(
            f"Unknown stage {name!r}. Declared: {', '.join(s.name for s in self.stages)}."
        )

    def contracts(self) -> tuple[Contract, ...]:
        """Every contract the pipeline touches, in stage order and without repeats."""
        seen: set[str] = set()
        out: list[Contract] = []
        for stage_spec in self.stages:
            if stage_spec.contract in seen:
                continue
            seen.add(stage_spec.contract)
            out.append(CONTRACTS.get(stage_spec.contract))
        return tuple(out)

    def validate(self, *, supplied: Sequence[str] = ()) -> None:
        """Check every stage's inputs are produced upstream or supplied with the batch.

        ``supplied`` names tensors that come from the training loop rather than
        from a stage, such as tokenised text and sampled query points.
        """
        available = set(supplied)
        for stage_spec in self.stages:
            missing = sorted(name for name in stage_spec.consumes if name not in available)
            if missing:
                raise ContractError(
                    f"Stage {stage_spec.name!r} consumes {missing}, which no earlier stage "
                    "produces and the batch does not supply."
                )
            available.update(stage_spec.produces)

    def parameter_estimate(
        self, vocabulary_sizes: Mapping[str, int] | None = None
    ) -> dict[str, int]:
        """Estimated parameters per component at the configured scale."""
        return estimate_parameters(self.scale_spec, vocabulary_sizes)

    def implemented_stages(self) -> tuple[str, ...]:
        """Stages that exist today."""
        return tuple(s.name for s in self.stages if s.implemented)

    def declared_stages(self) -> tuple[str, ...]:
        """Stages that are interfaces only."""
        return tuple(s.name for s in self.stages if not s.implemented)

    def summary(self) -> dict[str, object]:
        """Compact description for reports and tests."""
        return {
            "status": self.status,
            "scale": self.scale_spec.name,
            "stages": len(self.stages),
            "implemented": list(self.implemented_stages()),
            "declared": list(self.declared_stages()),
            "contracts": [contract.name for contract in self.contracts()],
        }


DEFAULT_SUPPLIED_TENSORS: tuple[str, ...] = (
    "text_tokens",
    "text_mask",
    "query_points",
    "entity_query_points",
    "active_tokens",
    "alignment_target",
    "align_image",
    "scene_lod",
    "scene_level",
)
"""Tensors the training loop supplies rather than a stage producing them."""


def trace_pipeline(
    scene: AWRScene,
    ontology: AnatomyOntology,
    *,
    architecture: LagnavArchitecture | None = None,
    batch_size: int = 2,
    query_points: int = 1024,
) -> dict[str, object]:
    """Run a shape-level pass of the whole pipeline from a real AWR scene.

    This is the architecture's smoke test. The first stage runs for real: an
    actual heart scene becomes contract-valid feature arrays. Every later stage is
    traced symbolically, resolving each declared output shape under one consistent
    set of dimension bindings.

    Returns a report naming, per stage, the tensors it produces and their resolved
    shapes, plus the bindings that held across the whole pipeline.
    """
    model = architecture or LagnavArchitecture()
    extractor = AWRFeatureExtractor(ontology)
    payload: dict[str, PlainArray] = extractor.encode_batch([scene] * batch_size)
    bindings = AWR_BATCH_CONTRACT.validate_payload(payload, bindings={"B": batch_size})
    bindings["P_QUERY"] = query_points
    bindings["N_CODEBOOK"] = len(extractor.codebook)

    model.validate(supplied=(*DEFAULT_SUPPLIED_TENSORS, *AWR_BATCH_CONTRACT.names()))

    known_contracts = (
        AWR_BATCH_CONTRACT,
        PROGRAM_CONTRACT,
        TEXT_CONTRACT,
        GRAPH_ENCODER_CONTRACT,
        LATENT_CONTRACT,
        SCENE_CONTEXT_CONTRACT,
        GEOMETRY_CONTRACT,
        ALIGNMENT_CONTRACT,
    )
    lookup = {contract.name: contract for contract in known_contracts}

    traced: dict[str, dict[str, tuple[int, ...]]] = {}
    for stage_spec in model.stages:
        contract = lookup[stage_spec.contract]
        shapes: dict[str, tuple[int, ...]] = {}
        for tensor_name in stage_spec.produces:
            try:
                spec = contract.spec(tensor_name)
            except ContractError:
                continue
            shapes[tensor_name] = spec.resolve(bindings)
        traced[stage_spec.name] = shapes

    return {
        "batch_size": batch_size,
        "bindings": dict(sorted(bindings.items())),
        "stages": traced,
        "real_tensors": {name: array.shape for name, array in sorted(payload.items())},
        "parameters": model.parameter_estimate(extractor.vocabulary_sizes()),
        "summary": model.summary(),
    }
