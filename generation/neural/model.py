"""The proposed Lagnav model, as a composition of declared stages.

STATUS: skeleton. The pipeline, its stages and their contracts are declared and
checked; no stage computes anything, and no framework is imported.

What this module is for
-----------------------

Two things that are worth having before a line of model code exists:

1. **A composition check.** :meth:`LagnavArchitecture.validate` proves every
   stage's inputs are produced by an earlier stage or supplied with the batch. A
   pipeline that does not compose on paper will not compose in a framework.
2. **A shape trace.** :func:`trace_pipeline` walks the whole pipeline with a real
   AWR batch at the front and resolved shapes everywhere after it, which is the
   closest thing to a forward pass that is honest at this stage. It catches the
   errors that are expensive later: a dimension meaning two things, a stage
   expecting a tensor nobody emits.
"""

